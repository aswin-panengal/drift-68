import { describe, expect, it } from 'vitest';
import { OpponentPoses } from '../src/game/core/RoomClient';
import { createSnapshot } from '../src/game/core/Simulation';
import { createLap, stepLap } from '../src/game/tracks/CheckpointManager';
import { TRACKS, TrackPath } from '../src/game/tracks/TrackConfigs';
import { POSE_BYTES, ROOM_TOKEN, encodePose, readPose, socketOrigin, type CarPose } from '../src/shared/multiplayer';
import { DEFAULT_SAVE, LAP_COUNTS } from '../src/shared/types';
import { validSnapshot } from '../src/shared/validation';

describe('ordered races', () => {
  for (const total of LAP_COUNTS) {
    it('finishes after exactly ' + total + (total === 1 ? ' lap' : ' laps'), () => {
      const path = new TrackPath(TRACKS.coastal);
      const lap = createLap(total);
      for (let completed = 1; completed <= total; completed++) {
        for (let next = 1; next <= path.checkpoints.length; next++) {
          const gate = path.checkpoints[next % path.checkpoints.length]!;
          const before = { x: gate.x - gate.tx, z: gate.z - gate.tz };
          const after = { x: gate.x + gate.tx, z: gate.z + gate.tz };
          const last = next === path.checkpoints.length;
          expect(stepLap(lap, after, before, path)).toBe(false);
          expect(stepLap(lap, before, after, path)).toBe(last && completed === total);
          expect(lap.completed).toBe(last ? completed : completed - 1);
        }
        if (completed < total) expect(lap).toMatchObject({ next: 1, checkpoint: 0, finished: false });
      }
    });
  }

  it('accepts solo snapshot data from before lap counts and rejects inconsistent newer counts', () => {
    const snapshot = createSnapshot(DEFAULT_SAVE);
    delete snapshot.lap.total;
    delete snapshot.lap.completed;
    expect(validSnapshot(snapshot)).toBe(true);
    snapshot.lap.total = 3;
    snapshot.lap.completed = 3;
    expect(validSnapshot(snapshot)).toBe(false);
  });
});

const pose: CarPose = { x: 0, z: 0, heading: 0, vx: 20, vz: 0 };
function packet(overrides: Partial<CarPose> = {}): ArrayBuffer {
  const buffer = new ArrayBuffer(POSE_BYTES);
  encodePose(buffer, { ...pose, ...overrides });
  return buffer;
}

describe('opponent snapshots', () => {
  it('validates a fixed-size packet and rejects nonfinite coordinates', () => {
    expect(POSE_BYTES).toBe(20);
    expect(readPose(packet())).toBe(true);
    expect(readPose(packet({ z: Infinity }))).toBe(false);
    expect(readPose(new ArrayBuffer(21))).toBe(false);
  });

  it('interpolates through the angle wrap and caps extrapolation after packet loss', () => {
    const poses = new OpponentPoses(), output = { ...pose };
    poses.push(packet({ heading: 3.1 }), 100);
    poses.push(packet({ x: 10, heading: -3.1 }), 200);
    expect(poses.sample(300, output)).toBe(true);
    expect(output.x).toBeCloseTo(5);
    expect(output.heading).toBeCloseTo(Math.PI);
    poses.sample(1200, output);
    expect(output.x).toBeCloseTo(12);
  });

  it('snaps to a reset and discards obsolete samples', () => {
    const poses = new OpponentPoses(), output = { ...pose };
    poses.push(packet({ x: 50 }), 100);
    poses.push(packet({ x: 100 }), 200);
    poses.sample(200, output);
    expect(output.x).toBe(100);
    poses.clear();
    expect(poses.sample(300, output)).toBe(false);
  });
});

it('allows one secure WebSocket origin without credentials, paths, or CSP delimiters', () => {
  expect(socketOrigin('wss://127.0.0.1:8787/')).toBe('wss://127.0.0.1:8787');
  for (const invalid of ['ws://localhost', 'https://localhost', 'wss://user@localhost', 'wss://localhost/race', 'wss://localhost?x=1', "wss://one.test;connect-src *"]) {
    expect(socketOrigin(invalid)).toBe('');
  }
});

it('accepts the resume tokens generated by released clients', () => {
  expect(ROOM_TOKEN.test(crypto.randomUUID())).toBe(true);
  expect(ROOM_TOKEN.test('-'.repeat(36))).toBe(false);
});
